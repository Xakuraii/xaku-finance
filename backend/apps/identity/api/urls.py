from django.urls import path

from apps.identity.api.views import (
    GoogleLoginView,
    LoginView,
    LogoutAllView,
    LogoutView,
    PasswordForgotView,
    PasswordResetView,
    ReauthView,
    RecoveryCodesView,
    RefreshView,
    RegisterView,
    ResendVerificationView,
    SessionDetailView,
    SessionListView,
    TwoFactorConfirmView,
    TwoFactorDisableView,
    TwoFactorSetupView,
    TwoFactorVerifyView,
    VerifyEmailView,
)

urlpatterns = [
    path("register/", RegisterView.as_view(), name="register"),
    path("login/", LoginView.as_view(), name="login"),
    path("refresh/", RefreshView.as_view(), name="refresh"),
    path("logout/", LogoutView.as_view(), name="logout"),
    path("logout-all/", LogoutAllView.as_view(), name="logout-all"),
    path("reauth/", ReauthView.as_view(), name="reauth"),
    path("sessions/", SessionListView.as_view(), name="session-list"),
    path("sessions/<uuid:session_id>/", SessionDetailView.as_view(), name="session-detail"),
    path("verify-email/", VerifyEmailView.as_view(), name="verify-email"),
    path(
        "verify-email/resend/",
        ResendVerificationView.as_view(),
        name="verify-email-resend",
    ),
    path("password/forgot/", PasswordForgotView.as_view(), name="password-forgot"),
    path("password/reset/", PasswordResetView.as_view(), name="password-reset"),
    path("google/", GoogleLoginView.as_view(), name="google-login"),
    path("2fa/setup/", TwoFactorSetupView.as_view(), name="two-factor-setup"),
    path("2fa/confirm/", TwoFactorConfirmView.as_view(), name="two-factor-confirm"),
    path("2fa/verify/", TwoFactorVerifyView.as_view(), name="two-factor-verify"),
    path("2fa/disable/", TwoFactorDisableView.as_view(), name="two-factor-disable"),
    path(
        "2fa/recovery-codes/",
        RecoveryCodesView.as_view(),
        name="two-factor-recovery-codes",
    ),
]
